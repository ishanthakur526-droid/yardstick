"""A made-up EPC project with the shape, and the traps, of a real one. No company's figures are in it.

It is the public demo when no real project is loaded, and the data every automatic test runs on. Its dynamics are
calibrated to what was measured on the one real project Yardstick was first built on (a power-distribution project,
16 items over 44 months), so the tool is judged on a realistic case rather than a convenient one:

  measured on the real project                          here
  everything delivered by 60% of the timeline           deliveries end at month 21 of 36, in lumpy lots
  3% to 34% bought beyond what was used (poles: 12%)    4% to 20% per item
  contractors held about 4 months of use                each district's contractors hold 3 to 5 months of use
  month-to-month use varied by about 70%                a monthly swing shared by all districts, plus each one's own
  roughly linear erection, tailing off at the end       a skewed hump per district, offset in time

It also carries the real project's traps and findings in miniature: material split evenly across districts that do
not use it evenly (so it has to be moved), one ratio in the master data that is wrong (the file says 0.25 lugs per
distribution box, the site uses about 5), bolts shared by two sets, identical rows that are both real entries,
zero-quantity rows, a goods receipt booked a month late, transfers sent but never booked in, and a closing store.

The calibration targets were taken from the real data before the planner was run on this sample; nothing here is
tuned to make the planner look good. `make_pack(seed)` is deterministic and returns the raw tables in the same layout
as a real data pack.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

SEED = 7
START = "2023-01"
N_MONTHS = 36
POLES = 24_000
RETURN_SHARE = 0.03  # of last month's issues, handed back by contractors
LAST_DELIVERY = 21  # deliveries end 60% into the timeline, as on the real project
DELIVERY_CHANCE = 0.6  # share of months in that window with a delivery (the real project: 25 of 44 months)
COMMON_SWING, OWN_SWING = 0.40, 0.40  # month-to-month variation shared by every district, and each district's own
OVERBUY = (0.04, 0.20)  # bought beyond what the site ends up using, per item

# code, name, share of all poles, first and last month of its work, months of use its contractors like to hold
DISTRICTS = [
    ("RB01", "RIVERBEND NORTH", 0.28, 0, 30, 3.5),
    ("RB02", "RIVERBEND EAST", 0.24, 1, 32, 4.0),
    ("RB03", "RIVERBEND SOUTH", 0.20, 2, 33, 4.5),
    ("RB04", "RIVERBEND WEST", 0.16, 3, 34, 3.0),
    ("RB05", "RIVERBEND HILLS", 0.12, 5, 35, 5.0),
]
CLOSING = ("RBCLS", "RIVERBEND CLOSING STORE")

# code, name, unit, lead time (days), role, decimals the quantity is kept to, what drives its use, per unit of the
# driver, month-to-month noise around the driver (lognormal sigma)
ITEMS = [
    ("SPO001", "PCC POLE 9 MTR 200 KG", "PCS", 150, "Independent", 0, "pole", 1.0, 0.0),
    ("SCL001", "POLE CLAMP SET", "SET", 90, "Parent", 0, "pole", 1.0, 0.10),
    ("SDB001", "SINGLE PHASE POLE-TOP DISTRIBUTION BOX", "NOS", 120, "Parent", 0, "pole", 0.12, 0.20),
    ("SEH001", "EYE HOOK", "NOS", 90, "Child", 0, "SCL001", 1.0, 0.08),
    ("SLU001", "ALUMINIUM LUG 25 SQMM", "NOS", 30, "Child", 0, "SDB001", 5.0, 0.15),
    ("SNB001", "HDG BOLTS AND NUTS WITH WASHER", "KG", 90, "Child", 1, "bolts", 1.0, 0.15),
    ("SCA001", "LT AB CABLE 3X95+1X70+1X16 SQMM", "KM", 60, "Independent", 3, "pole", 0.035, 0.25),
    ("SSC001", "SUSPENSION CLAMP", "NOS", 90, "Independent", 0, "pole", 0.9, 0.20),
    ("SGW001", "GI STAY WIRE 7/10", "MT", 90, "Independent", 3, "pole", 0.004, 0.30),
]
BOLTS_PER = {"SCL001": 0.5, "SDB001": 1.2}  # kg of bolts the site really uses per clamp set and per box
# The master data's sets: set_no, parent, child, ratio as the file states it.
SETS = [
    (1.0, "SCL001", "SEH001", 1.0),
    (1.0, "SCL001", "SNB001", 0.5),
    (2.0, "SDB001", "SLU001", 0.25),  # wrong: the site uses about 5 lugs per box
    (2.0, "SDB001", "SNB001", 1.2),
]
META = {
    "project": "Riverbend distribution upgrade",
    "company": "sample data",
    "source": "a synthetic sample generated by Yardstick, not any company's real figures",
    "about": (
        "A made-up power-distribution project: five districts, three years, nine items. It has the shape and the traps "
        "of a real stores extract (deliveries running far ahead of the work, contractors drawing ahead, a wrong ratio "
        "in the master data, a closing store at the end) and none of any company's numbers."
    ),
    "anchor_code": "SPO001",
    "anchor_noun": "pole",
    "closing_stores": CLOSING[1],
    "requisition_example": "1500",
    "sample": "1",
}


def _noise(rng: np.random.Generator, sigma: float, shape: tuple[int, ...]) -> np.ndarray:
    if sigma <= 0:
        return np.ones(shape)
    return rng.lognormal(-(sigma**2) / 2, sigma, shape)  # mean 1


def _profile(first: int, last: int) -> np.ndarray:
    """Share of a district's work done in each month: a hump that rises quickly and tails off slowly."""
    x = (np.arange(N_MONTHS) - first + 0.5) / (last - first + 1)
    w = np.where((x > 0) & (x < 1), np.clip(x, 0, 1) ** 1.1 * np.clip(1 - x, 0, 1) ** 1.4, 0.0)
    return w / w.sum()


def _usage(rng: np.random.Generator) -> dict[str, np.ndarray]:
    """What each district really used, month by month, per item."""
    shape = (N_MONTHS, len(DISTRICTS))
    work = np.column_stack([_profile(d[3], d[4]) * POLES * d[2] for d in DISTRICTS])
    swing = _noise(rng, COMMON_SWING, (N_MONTHS, 1)) * _noise(rng, OWN_SWING, shape)
    use = {"SPO001": np.round(work * swing)}
    spec = {i[0]: i for i in ITEMS}
    for code in ("SCL001", "SDB001", "SEH001", "SLU001", "SNB001", "SCA001", "SSC001", "SGW001"):
        _, _, _, _, _, dec, driver, per, sigma = spec[code]
        if driver == "bolts":
            base = sum(use[p] * kg for p, kg in BOLTS_PER.items())
        else:
            base = use["SPO001"] if driver == "pole" else use[driver]
        use[code] = np.round(base * per * _noise(rng, sigma, shape), dec)
    return use


def _push_plan(rng: np.random.Generator, total_use: float, dec: int) -> tuple[np.ndarray, float]:
    """The tender's quantity, delivered ahead of the work in lumpy lots and split evenly across districts (the plan
    does not know where the work will be)."""
    boq = round(total_use * (1 + rng.uniform(*OVERBUY)), dec)
    g = len(DISTRICTS)
    window = np.arange(LAST_DELIVERY + 1)
    on = rng.random(len(window)) < DELIVERY_CHANCE
    on[0] = on[-1] = True
    taper = np.clip(1.0 - (window - 15) / 6 * 0.7, 0.3, 1.0)  # most of it lands in the first 45% of the timeline
    sizes = rng.uniform(0.6, 1.4, int(on.sum())) * taper[on]
    lots = np.floor(boq * sizes / sizes.sum() / g * 10**dec) / 10**dec
    plan = np.zeros((N_MONTHS, g))
    plan[window[on]] = lots[:, None]
    plan[LAST_DELIVERY, 0] += round(boq - plan.sum(), dec)  # the remainder lands with the last lot
    return plan, boq


def _run_item(use: np.ndarray, plan: np.ndarray, dec: int) -> dict:
    """Play the project out month by month: deliveries, an emergency buy only when the whole site would otherwise
    stop, transfers between districts, issues to contractors (who draw ahead), returns, and the wind-down."""
    t_len, g_len = use.shape
    draw = np.array([d[5] for d in DISTRICTS])
    received = plan.copy()
    stock, held, last_issue = np.zeros(g_len), np.zeros(g_len), np.zeros(g_len)
    issue, ret = np.zeros((t_len, g_len)), np.zeros((t_len, g_len))
    moves: list[tuple[int, int, int | None, float]] = []
    for t in range(t_len):
        stock += received[t]
        back = np.minimum(np.round(RETURN_SHARE * last_issue, dec), np.maximum(held, 0.0))
        held -= back
        stock += back
        ret[t] = back
        must = np.maximum(0.0, use[t] - held)  # what contractors must get this month or the work stops
        ahead = use[t + 1] if t + 1 < t_len else np.zeros(g_len)
        want = np.round(np.maximum(must, use[t] + draw * ahead - held), dec)  # what they ask for
        lack = float(must.sum() - stock.sum())
        if lack > 0:  # the whole site would stop: buy in a hurry
            gap = np.maximum(0.0, must - stock)
            extra = np.ceil(gap / gap.sum() * lack * 1.1 * 10**dec) / 10**dec
            received[t] += extra
            stock += extra
        # Moves between districts: first so that no district stops, then so contractors get what they ask for while
        # the giver keeps a month's use in hand.
        for target, keep in ((must, must), (want, want + use[t])):
            need = np.maximum(0.0, target - stock)
            spare = np.maximum(0.0, stock - keep)
            for j in np.argsort(-need):
                if need[j] <= 0:
                    break
                for i in np.argsort(-spare):
                    if i == j or spare[i] <= 0:
                        continue
                    q = round(float(np.ceil(min(need[j], spare[i]) * 10**dec) / 10**dec), dec)
                    q = min(q, round(float(spare[i]), dec))
                    if q <= 0:
                        continue
                    stock[i] -= q
                    stock[j] += q
                    spare[i] -= q
                    need[j] -= q
                    moves.append((t, int(i), int(j), q))
                    if need[j] <= 1e-9:
                        break
        out = np.round(np.minimum(want, stock), dec)
        stock -= out
        held += out - use[t]
        issue[t] = out
        last_issue = out
    for g in range(g_len):  # the project winds up: what is left goes to the closing store
        left = round(float(stock[g]), dec)
        if left > 0:
            moves.append((t_len - 1, g, None, left))
    return {"received": received, "issue": issue, "ret": ret, "moves": moves}


def _split(rng: np.random.Generator, qty: float, dec: int, most: int) -> list[float]:
    """One month's quantity as a few entries, as a stores clerk would book it."""
    n = int(rng.integers(1, most + 1))
    if n == 1 or qty < n * 10.0**-dec * 2:
        return [qty]
    parts = np.round(rng.dirichlet(np.ones(n)) * qty, dec)
    parts[-1] = round(qty - parts[:-1].sum(), dec)
    return [float(p) for p in parts] if (parts > 0).all() else [qty]


def make_pack(seed: int = SEED) -> dict[str, pd.DataFrame]:
    """The raw tables of a made-up project: items, sets, receipts, transfers, contractor_moves, plus meta and boq."""
    rng = np.random.default_rng(seed)
    months = pd.period_range(START, periods=N_MONTHS, freq="M")
    starts = months.to_timestamp().values.astype("datetime64[D]")
    yymm = [m.strftime("%y%m") for m in months]
    use = _usage(rng)
    rec_rows, tr_rows, cm_rows, boq_rows = [], [], [], []
    grn = voucher = 0
    for code, _name, _unit, _lead, _role, dec, *_ in ITEMS:
        plan, boq = _push_plan(rng, float(use[code].sum()), dec)
        boq_rows.append((code, boq))
        run = _run_item(use[code], plan, dec)
        for t in range(N_MONTHS):
            for g, (_gcode, gname, *_r) in enumerate(DISTRICTS):
                if run["received"][t, g] > 0:
                    for q in _split(rng, float(run["received"][t, g]), dec, 2):
                        grn += 1
                        rec_rows.append((t, int(rng.integers(0, 28)), f"GRN/{yymm[t]}/{grn:05d}", code, gname, q))
                for kind, arr, most in (("ISSUE", run["issue"], 4), ("RETURN", run["ret"], 1)):
                    if arr[t, g] > 0:
                        for q in _split(rng, float(arr[t, g]), dec, most):
                            cm_rows.append((t, int(rng.integers(0, 28)), kind, code, gname, q))
            used_t = round(float(use[code][t].sum()), dec)
            if used_t > 0:
                for q in _split(rng, used_t, dec, 5):
                    cm_rows.append((t, int(rng.integers(0, 28)), "CONSUMPTION", code, None, q))
        for t, i, j, q in run["moves"]:
            voucher += 1
            d = int(rng.integers(0, 28))
            src, dst = DISTRICTS[i], (CLOSING if j is None else DISTRICTS[j][:2])
            kinds = (
                ("Issue to the closing store", "Receipt at the closing store")
                if j is None
                else ("Issue to another store", "Receipt from another store")
            )
            tr_rows.append((t, d, f"TO/{yymm[t]}/{voucher:05d}", kinds[0], "OUT", code, src[0], src[1], q))
            tr_rows.append((t, d, f"TI/{yymm[t]}/{voucher:05d}", kinds[1], "IN", code, dst[0], dst[1], q))

    receipts = pd.DataFrame(rec_rows, columns=["t", "d", "grn_no", "item_code", "godown", "qty_received"])
    transfers = pd.DataFrame(
        tr_rows,
        columns=["t", "d", "voucher_no", "voucher_type", "direction", "item_code", "godown_code", "godown", "qty"],
    )
    moves = pd.DataFrame(cm_rows, columns=["t", "d", "type", "item_code", "godown", "qty"])

    # Traps a real stores extract has.
    # 1. A goods receipt entered a month late: the cable's first lot at Hills is booked on the 2nd of month two,
    #    although contractors were already issued from it, so that godown's running stock dips below zero for a month.
    late = receipts.index[
        (receipts["item_code"] == "SCA001") & (receipts["godown"] == "RIVERBEND HILLS") & (receipts["t"] == 0)
    ]
    receipts.loc[late, "t"] = 1
    receipts.loc[late, "d"] = 1
    # 2. A few transfers sent but never booked in at the other end (1% of moves between districts, small ones).
    ins = transfers[transfers["voucher_type"] == "Receipt from another store"]
    small = ins[ins["qty"] <= ins["qty"].quantile(0.25)].index
    transfers = transfers.drop(index=rng.choice(small, size=max(1, len(ins) // 100), replace=False))
    # 3. Identical rows that are both real entries (0.5% of goods receipts), and zero-quantity rows (about 1%).
    twins = receipts.loc[rng.choice(receipts.index, size=max(1, len(receipts) // 200), replace=False)]
    zeros = moves.loc[rng.choice(moves.index, size=max(1, len(moves) // 100), replace=False)].assign(qty=0.0)
    blank = receipts.loc[rng.choice(receipts.index, size=2, replace=False)].assign(qty_received=0.0)
    receipts = pd.concat([receipts, twins, blank])
    moves = pd.concat([moves, zeros])

    spec = {i[0]: i for i in ITEMS}

    def tidy(df: pd.DataFrame, columns: list[str]) -> pd.DataFrame:
        when = starts[df["t"].to_numpy()] + df["d"].to_numpy().astype("timedelta64[D]")
        df = df.assign(
            date=when.astype(str),
            item_name=df["item_code"].map(lambda c: spec[c][1]),
            unit=df["item_code"].map(lambda c: spec[c][2]),
        )
        return df.sort_values(["t", "d"], kind="stable")[columns].reset_index(drop=True)

    items = pd.DataFrame(
        [(c, n, u, lead, role) for c, n, u, lead, role, *_ in ITEMS],
        columns=["item_code", "item_name", "unit", "lead_time_days", "role"],
    )
    sets = pd.DataFrame(
        [(no, p, spec[p][1], spec[p][2], c, spec[c][1], spec[c][2], r) for no, p, c, r in SETS],
        columns=[
            "set_no",
            "parent_code",
            "parent_name",
            "parent_unit",
            "child_code",
            "child_name",
            "child_unit",
            "ratio_of_parent",
        ],
    )
    return {
        "items": items,
        "sets": sets,
        "receipts": tidy(receipts, ["date", "grn_no", "item_code", "item_name", "unit", "godown", "qty_received"]),
        "transfers": tidy(
            transfers,
            [
                "date",
                "voucher_no",
                "voucher_type",
                "direction",
                "item_code",
                "item_name",
                "unit",
                "godown_code",
                "godown",
                "qty",
            ],
        ),
        "contractor_moves": tidy(moves, ["date", "type", "item_code", "item_name", "unit", "godown", "qty"]),
        "meta": pd.DataFrame(list(META.items()), columns=["key", "value"]),
        "boq": pd.DataFrame(boq_rows, columns=["item_code", "qty"]),
    }
